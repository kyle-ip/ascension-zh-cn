def ascii_sub(text: str, en: str, zh: str) -> str:
    """Replace `en` when not inside another ASCII word. CJK is a valid boundary."""
    return re.sub(rf"(?<![A-Za-z']){re.escape(en)}(?![A-Za-z'])", zh, text)


def apply_words(text: str) -> str:
    out = text
    for pat, zh in _EFFECT_WORD_RES:
        out = pat.sub(zh, out)
    out = _SPACE_RE.sub(" ", out)
    out = _PUNCT_SPACE_RE.sub(r"\1", out)
    return out.strip()


def polish_copy(text: str) -> str:
    """Collapse leftover English function words and tidy punctuation."""
    out = text.replace("'s", "之")
    out = _SPACE_RE.sub(" ", out)
    out = re.sub(r" +([，。；：？！,.])", r"\1", out)
    out = re.sub(r"([，。；：])\.", r"\1", out)
    out = out.replace("..", "。").replace(" .", "。").replace(" ,", "，")
    out = re.sub(r"([\u4e00-\u9fff]) ([A-Za-z])", r"\1\2", out)
    out = re.sub(r"([A-Za-z]) ([\u4e00-\u9fff])", r"\1\2", out)
    out = re.sub(r"([\u4e00-\u9fff]) ([\u4e00-\u9fff])", r"\1\2", out)
    out = _SPACE_RE.sub(" ", out)
    return out.strip()


