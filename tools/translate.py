def translate_flavor(text: str) -> str:
    if not text:
        return ""
    plain = strip_drop_cap(text).strip().strip('"')
    if plain in FLAVOR_EXACT:
        return FLAVOR_EXACT[plain]
    collapsed = re.sub(r"\s+", " ", plain)
    for en, zh in FLAVOR_EXACT.items():
        if re.sub(r"\s+", " ", en.strip().strip('"')) == collapsed:
            return zh
    raw, tokens = protect_tokens(text)
    raw = apply_card_names(raw)
    raw = _apply_name_parts(raw)
    raw = apply_phrases(raw, _EFFECT_PHRASES_SORTED)
    raw = apply_words(raw)
    raw = polish_copy(raw)
    return restore_tokens(raw, tokens)


def translate_label(text: str) -> str:
    mapping = [
        ("Ongoing Trophy:", "持续战利品："),
        ("Event Trophy:", "事件战利品："),
        ("MULTI-UNITE:", "多重联合："),
        ("Rally: Enlightened", "集结：圣贤"),
        ("Rally: Lifebound", "集结：命约"),
        ("Rally: Mechana", "集结：机械"),
        ("Rally: Void", "集结：虚空"),
        ("Rally: Monster", "集结：怪物"),
        ("Reward:", "奖励："),
        ("FATE:", "天命："),
        ("Fate:", "天命："),
        ("Trophy:", "战利品："),
        ("Unite:", "联合："),
        ("Energize", "充能"),
        ("ONGOING:", "持续："),
        ("DAY:", "昼："),
        ("NIGHT:", "夜："),
        ("INFEST - ", "感染 - "),
        ("SERENITY:", "宁静："),
        ("ECHO:", "回响："),
        ("Dreambind:", "梦缚："),
    ]
    raw, tokens = protect_tokens(text)
    for en, zh in sorted(mapping, key=lambda x: len(x[0]), reverse=True):
        raw = raw.replace(en, zh)
        raw = raw.replace(en.upper(), zh)
        raw = raw.replace(en.title(), zh)
    return restore_tokens(raw, tokens)
