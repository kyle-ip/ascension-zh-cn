def protect_tokens(text: str) -> tuple[str, list[str]]:
    tokens: list[str] = []

    def stash(m: re.Match) -> str:
        tokens.append(m.group(0))
        return f"\x00T{len(tokens) - 1}\x00"

    out = re.sub(r"\$\{[^}]+\}", stash, text)
    out = re.sub(r"<sprite=[^>]+>", stash, out)
    out = re.sub(r"</?[A-Za-z][^>]*>", stash, out)
    return out, tokens


def restore_tokens(text: str, tokens: list[str]) -> str:
    def unstash(m: re.Match) -> str:
        return tokens[int(m.group(1))]

    return re.sub(r"\x00T(\d+)\x00", unstash, text)


def strip_drop_cap(text: str) -> str:
    text = text.replace("\ufffd", "Ae").replace("Æ", "Ae").replace("æ", "ae")
    text = re.sub(
        r"<size=\s*[^>]*>\s*(.*?)\s*</size>(?:<space=[^>]*>)?",
        r"\1",
        text,
        flags=re.I,
    )
    text = text.replace("HSedron", "Hedron")
    return text


def _compile_ascii_pairs(pairs: list[tuple[str, str]]) -> list[tuple[re.Pattern[str], str]]:
    seen: set[str] = set()
    compiled: list[tuple[re.Pattern[str], str]] = []
    for en, zh in sorted(pairs, key=lambda x: len(x[0]), reverse=True):
        if not en or en in seen:
            continue
        seen.add(en)
        compiled.append((re.compile(rf"(?<![A-Za-z']){re.escape(en)}(?![A-Za-z'])"), zh))
        if en.isalpha():
            compiled.append((re.compile(rf"(?<![A-Za-z']){re.escape(en)}'s(?![A-Za-z'])"), zh + "之"))
    return compiled


