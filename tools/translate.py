def translate_effect(text: str) -> str:
    if not text:
        return ""
    raw, tokens = protect_tokens(text)
    raw = apply_phrases(raw, _EFFECT_PHRASES_SORTED)
    raw = apply_card_names(raw)
    raw = _apply_name_parts(raw)
    raw = re.sub(r"(\d+)R\b", r"\1符文", raw)
    raw = re.sub(r"(\d+)P\b", r"\1战力", raw)
    raw = re.sub(r"(\d+)H\b", r"\1荣誉", raw)
    raw = re.sub(r"(\d+)I\b", r"\1洞察", raw)
    raw = apply_words(raw)
    raw = polish_copy(raw)
    return restore_tokens(raw, tokens)


def _apply_name_parts(text: str) -> str:
    out = text
    for en, zh in _NAME_PARTS_SORTED:
        out = out.replace(en, zh)
    for pat, zh in _NAME_WORD_RES:
        out = pat.sub(zh, out)
    return out


def translate_name(text: str) -> str:
    if not text:
        return ""
    base = strip_drop_cap(text).strip()
    base = re.sub(r"\s+", " ", base)
    key = re.sub(r"\s+(10TH|SoS|RoV|RU|v2)$", "", base, flags=re.I).strip()
    if key in NAME_EXACT:
        suffix = base[len(key) :].strip()
        return NAME_EXACT[key] if not suffix else NAME_EXACT[key]
    if base in NAME_EXACT:
        return NAME_EXACT[base]
    for en, zh in sorted(NAME_PHRASES, key=lambda x: len(x[0]), reverse=True):
        if base == en or key == en:
            return zh
        if en in base and len(en) > 8:
            base = base.replace(en, zh)
    out = _apply_name_parts(base)
    for en, zh in sorted(NAME_SUFFIXES, key=lambda x: len(x[0]), reverse=True):
        out = out.replace(en, zh)
    out = re.sub(r"\b(of|Of|the|The)\b", "", out)
    out = re.sub(r"'s\b", "之", out)
    out = out.replace(",", "·").replace(":", "：").replace(" - ", "：")
    out = re.sub(r"\s+", "", out)
    out = out.replace("··", "·").strip("·")
    return out


